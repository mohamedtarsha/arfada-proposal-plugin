"""assemble_draft.py — assemble generated sections into proposal_draft.md.

Usage:
    python scripts/assemble_draft.py <run_dir>

Concatenates all READY sections in blueprint order into proposal_draft.md,
preserving headings, paragraphs, bullets, numbered lists, tables, and
NEEDS_ARFADA_EVIDENCE placeholders. Also produces a generation coverage summary.
No DOCX. No LLM, no network.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

_SCRIPT_DIR = Path(__file__).resolve().parent
_PLUGIN_ROOT = _SCRIPT_DIR.parent
if str(_PLUGIN_ROOT) not in sys.path:
    sys.path.insert(0, str(_PLUGIN_ROOT))

from engine.tor.generation import section_to_markdown, NEEDS_EVIDENCE_TAG


def _out(data: dict) -> None:
    s = json.dumps(data, ensure_ascii=False, indent=2)
    sys.stdout.buffer.write((s + "\n").encode("utf-8"))
    sys.stdout.buffer.flush()


def _err(msg: str, code: int = 1) -> None:
    sys.stderr.buffer.write((json.dumps({"error": msg}) + "\n").encode("utf-8"))
    sys.exit(code)


def _read_json(path: Path) -> dict:
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def main(argv=None) -> int:
    args = argv or sys.argv[1:]
    if not args:
        _err("Usage: assemble_draft.py <run_dir>")
    run_dir = Path(args[0]).expanduser().resolve()
    bp_path = run_dir / "proposal_blueprint.json"
    if not bp_path.exists():
        _err("proposal_blueprint.json missing — run build_blueprint.py first", 2)

    blueprint = _read_json(bp_path)
    status_doc = _read_json(run_dir / "generation_status.json")
    sections_dir = run_dir / "generated_sections"

    tor = _read_json(run_dir / "tor_analysis.json")
    meta = tor.get("metadata", {})
    title = ""
    if isinstance(meta.get("assignment"), dict):
        title = meta["assignment"].get("value", "").strip()

    # --- assemble in blueprint order ---
    ordered = sorted(blueprint["sections"], key=lambda s: s["sequence"])
    parts: list[str] = []
    proposal_title = title or "Technical Proposal"
    parts.append(f"# {proposal_title}\n")
    parts.append(f"*Draft generated by ARFADA Proposal Plugin v0.4.0 — "
                 f"run {blueprint.get('run_id')}*\n")

    ready = blocked = skipped = 0
    for sec in ordered:
        sid = sec["section_id"]
        st = status_doc["sections"].get(sid, {}).get("status")
        if st == "READY":
            cand_path = sections_dir / f"{sid}.json"
            if cand_path.exists():
                candidate = _read_json(cand_path)
                parts.append(section_to_markdown(candidate, sec["title"]))
                ready += 1
        elif st == "BLOCKED_BY_DECISION":
            parts.append(f"## {sec['title']}\n\n> **BLOCKED_BY_DECISION** — "
                         f"resolve the dependent proposal decisions, then regenerate.\n")
            blocked += 1
        else:
            skipped += 1

    draft = "\n".join(parts).rstrip() + "\n"
    (run_dir / "proposal_draft.md").write_text(draft, encoding="utf-8")

    # --- coverage report ---
    coverage = _coverage(run_dir, blueprint, status_doc)
    _out({
        "status": "ok",
        "proposal_draft": "proposal_draft.md",
        "sections_ready": ready,
        "sections_blocked": blocked,
        "sections_skipped": skipped,
        "coverage": coverage,
    })
    return 0


def _coverage(run_dir: Path, blueprint: dict, status_doc: dict) -> dict:
    """Generation-level coverage: requirement response ledger rollup."""
    sections_dir = run_dir / "generated_sections"
    total_mandatory = sum(len(s.get("mandatory_requirement_ids", []))
                          for s in blueprint["sections"])
    addressed = partial = missing = blocked_dec = blocked_ev = 0

    for s in blueprint["sections"]:
        sid = s["section_id"]
        st = status_doc["sections"].get(sid, {}).get("status")
        if st == "BLOCKED_BY_DECISION":
            blocked_dec += len(s.get("mandatory_requirement_ids", []))
            continue
        cand_path = sections_dir / f"{sid}.json"
        if not cand_path.exists():
            missing += len(s.get("mandatory_requirement_ids", []))
            continue
        with cand_path.open(encoding="utf-8") as f:
            candidate = json.load(f)
        for entry in candidate.get("requirement_response_ledger", []):
            status = entry.get("status")
            if status == "ADDRESSED":
                addressed += 1
            elif status == "PARTIAL":
                partial += 1
            elif status == "MISSING":
                missing += 1
            elif status == "BLOCKED_BY_DECISION":
                blocked_dec += 1
            elif status == "BLOCKED_BY_MISSING_EVIDENCE":
                blocked_ev += 1

    return {
        "total_mandatory_bidder_requirements": total_mandatory,
        "addressed": addressed,
        "partial": partial,
        "missing": missing,
        "blocked_by_decision": blocked_dec,
        "blocked_by_missing_evidence": blocked_ev,
    }


if __name__ == "__main__":
    sys.exit(main())
